"""
GripWise — Mock inference provider.
Returns deterministic, clearly labelled demo analysis. Never claims to be real AI.
"""
import hashlib
import time
from ai.interfaces import (
    InferenceResult, TyreObservation, ConfidenceTier, RecommendedAction
)

VERSION = "mock-0.1.0"

# Scenario buckets based on image hash so results are deterministic
def _bucket(image_bytes: bytes) -> int:
    digest = hashlib.md5(image_bytes).hexdigest()
    return int(digest[:2], 16) % 4   # 0..3


class MockProvider:
    """
    Deterministic mock provider for local demo / CI.

    All outputs are labelled provider='mock'. No computer vision is performed.
    The result varies by image content hash to allow UI testing of different states.
    """

    def analyse(self, image_bytes: bytes) -> InferenceResult:
        t0 = time.perf_counter()
        bucket = _bucket(image_bytes)

        if len(image_bytes) < 1000:
            # Treat very small payloads as quality failure
            return InferenceResult(
                provider="mock",
                model_version=VERSION,
                image_quality="FAIL",
                quality_issues=["IMAGE_TOO_SMALL", "TYRE_NOT_FOUND"],
                detected_tyres=0,
                recommended_action=RecommendedAction.ANALYSIS_FAILED,
                recommended_action_explanation="Image is too small or does not contain a detectable tyre.",
                observations=[],
                raw_scores={},
                inference_ms=round((time.perf_counter() - t0) * 1000, 1),
            )

        scenarios = [
            _scenario_ok,
            _scenario_monitor,
            _scenario_inspect_soon,
            _scenario_not_available,
        ]
        result = scenarios[bucket](image_bytes)
        result.inference_ms = round((time.perf_counter() - t0) * 1000, 1)
        return result

    def health(self) -> dict:
        return {
            "provider": "mock",
            "model_version": VERSION,
            "detection_available": False,
            "tread_analysis_available": False,
            "anomaly_detection_available": False,
            "condition_classifier_available": False,
            "note": (
                "Mock provider active. All outputs are demo data. "
                "Set INFERENCE_PROVIDER=cv_pipeline to use real analysis."
            ),
        }


# ─────────── Scenario helpers ───────────

def _base_observations(tread: float, tier: ConfidenceTier) -> list[TyreObservation]:
    return [
        TyreObservation(
            field="tread_score",
            value=round(tread, 1),
            confidence=tier,
            explanation="[DEMO] Relative wear indicator based on simulated edge density analysis.",
            caveat=(
                "This is a relative wear indicator derived from image pixel analysis. "
                "It is NOT a tread depth measurement in mm and has NOT been calibrated "
                "against physical measurements. This result was generated by a mock provider — "
                "it does NOT represent real AI analysis."
            ),
        ),
        TyreObservation(
            field="anomaly_detected",
            value=tread < 35,
            confidence=ConfidenceTier.LOW,
            explanation="[DEMO] Simulated anomaly flag based on mock tread threshold.",
            caveat="Demo output — no real image analysis was performed.",
        ),
        TyreObservation(
            field="condition_class",
            value=None,
            confidence=ConfidenceTier.NOT_AVAILABLE,
            explanation="Condition classifier is not available in this deployment.",
            caveat=None,
        ),
    ]


def _scenario_ok(img: bytes) -> InferenceResult:
    return InferenceResult(
        provider="mock", model_version=VERSION,
        image_quality="PASS", quality_issues=[],
        detected_tyres=1,
        recommended_action=RecommendedAction.OK,
        recommended_action_explanation="[DEMO] Tread indicator is healthy. No action required.",
        observations=_base_observations(74.2, ConfidenceTier.MEDIUM),
        raw_scores={"tread_score": 74.2, "groove_count": 6, "edge_density": 0.18},
        inference_ms=0.0,
    )


