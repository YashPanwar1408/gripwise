@pytest.mark.asyncio
async def test_list_inspections(client):
    token, tpid = await _setup_rider_with_tyre(client)
    headers = {"Authorization": f"Bearer {token}"}

    await client.post("/api/inspections", data={"tyre_position_id": tpid}, files={"image": ("t.jpg", io.BytesIO(VALID_IMAGE), "image/jpeg")}, headers=headers)
    resp = await client.get("/api/inspections", headers=headers)
    assert resp.status_code == 200
    assert len(resp.json()["data"]["inspections"]) >= 1


@pytest.mark.asyncio
async def test_inspection_other_rider_cannot_access(client):
    token1, tpid1 = await _setup_rider_with_tyre(client)
    token2, _ = await _setup_rider_with_tyre(client)

    subm = await client.post("/api/inspections", data={"tyre_position_id": tpid1}, files={"image": ("t.jpg", io.BytesIO(VALID_IMAGE), "image/jpeg")}, headers={"Authorization": f"Bearer {token1}"})
    insp_id = subm.json()["data"]["inspection_id"]

    resp = await client.get(f"/api/inspections/{insp_id}", headers={"Authorization": f"Bearer {token2}"})
    assert resp.status_code == 404
