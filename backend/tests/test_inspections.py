# Pad to > 1 KB so it doesn't hit the tiny-image path in mock provider
VALID_IMAGE = MINIMAL_JPEG + b"\x00" * 2000


async def _setup_rider_with_tyre(client):
    """Helper: register rider, create vehicle, add tyre position. Returns (token, tyre_position_id)."""
    import uuid
    email = f"insp_{uuid.uuid4().hex[:8]}@test.com"
    await client.post("/api/auth/register", json={
        "display_name": "Insp Rider",
        "email": email,
        "password": "password123",
        "role": "RIDER",
    })
    login = await client.post("/api/auth/login", json={"credential": email, "password": "password123"})
    token = login.json()["data"]["access_token"]
    headers = {"Authorization": f"Bearer {token}"}

    vresp = await client.post("/api/vehicles", json={"make": "Honda", "model": "CB", "vehicle_type": "MOTORCYCLE"}, headers=headers)
    vid = vresp.json()["data"]["vehicle_id"]

    tpresp = await client.post(f"/api/vehicles/{vid}/tyre-positions", json={"position": "FRONT"}, headers=headers)
    tpid = tpresp.json()["data"]["tyre_position_id"]
    return token, tpid


@pytest.mark.asyncio
async def test_submit_inspection_success(client):
    token, tpid = await _setup_rider_with_tyre(client)
    resp = await client.post(
        "/api/inspections",
        data={"tyre_position_id": tpid},
        files={"image": ("tyre.jpg", io.BytesIO(VALID_IMAGE), "image/jpeg")},
        headers={"Authorization": f"Bearer {token}"},
    )
    assert resp.status_code == 202
    data = resp.json()["data"]
    assert "inspection_id" in data
    assert data["status"] == "PENDING"


@pytest.mark.asyncio
async def test_submit_wrong_content_type(client):
    token, tpid = await _setup_rider_with_tyre(client)
    resp = await client.post(
        "/api/inspections",
        data={"tyre_position_id": tpid},
        files={"image": ("file.pdf", io.BytesIO(b"%PDF-test-content-padding" * 100), "application/pdf")},
        headers={"Authorization": f"Bearer {token}"},
    )
    assert resp.status_code == 415


